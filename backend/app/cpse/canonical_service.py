def generate_prototype_code(index: int) -> str:
    """
    Generates a deterministic prototype code:
    e.g., index 1 -> NMM-000001
    NMM = National Material Master prototype identifier.
    """
    return f"NMM-{index:06d}"


def generate_canonical_description(source: Dict[str, Any]) -> str:
    """
    Synthesizes a standardized, professional canonical description from source material data.
    Preserves all technical tokens (dimensions, grades, specifications) without hallucinating.
    """
    raw_desc = (source.get("description") or "").strip()
    spec = (source.get("specification") or "").strip()
    grade = (source.get("material_grade") or "").strip()
    dimensions = (source.get("dimensions") or "").strip()

    # Clean redundant whitespace
    raw_desc = re.sub(r"\s+", " ", raw_desc)

    # Convert all-caps string to title-cased words while preserving technical abbreviations
    words = raw_desc.split(" ")
    formatted_words = []
    UPPERCASE_TOKENS = {
        "SS304", "SS316", "SS316L", "SS304L", "A106", "A106-B", "ASTM", "ASME",
        "DIN", "ISO", "IS", "IEC", "WCB", "CF8M", "NB", "SCH", "SCH40", "SCH80",
        "LR", "SR", "BW", "SW", "NPT", "BSP", "BSPT", "ANSI", "API", "EA", "NOS",
        "MTR", "LTR", "KG", "SET", "HV", "LV", "MV", "DC", "AC", "LED", "PVC",
        "XLPE", "FRLS", "GI", "MS", "CS", "CI", "DI", "SS", "PTFE", "EPDM", "NBR",
        "M10", "M12", "M16", "M20", "M24", "M8", "M6", "PN10", "PN16", "PN25", "PN40",
        "150#", "300#", "600#", "SQ", "MM", "MM2", "KM", "KV", "KW", "HP", "RPM"
    }

    for w in words:
        clean_w = w.rstrip(",.;:()")
        upper_w = clean_w.upper()
        punct = w[len(clean_w):] if len(w) > len(clean_w) else ""
        if upper_w in UPPERCASE_TOKENS or any(char.isdigit() for char in upper_w):
            formatted_words.append(upper_w + punct)
        elif len(upper_w) <= 2:
            formatted_words.append(upper_w + punct)
        else:
            formatted_words.append(clean_w.capitalize() + punct)

    desc_clean = " ".join(formatted_words)

    # Check if spec or grade or dimensions are already in desc
    extra_parts = []
    desc_lower = desc_clean.lower()
    if grade and grade.lower() not in desc_lower and grade.lower() != "n/a":
        extra_parts.append(grade)
    if dimensions and dimensions.lower() not in desc_lower and dimensions.lower() != "n/a":
        extra_parts.append(dimensions)
    if spec and spec.lower() not in desc_lower and spec.lower() != "n/a":
        if len(spec) < 60:
            extra_parts.append(spec)

    if extra_parts:
        return f"{desc_clean} {' '.join(extra_parts)}".strip()
    return desc_clean


def determine_canonical_category(source: Dict[str, Any]) -> str:
    """
    Determines commodity / procurement category using source attributes or keyword rules.
    Falls back to 'Unclassified' if uncertain, preventing arbitrary category fabrication.
    """
    src_cat = (source.get("category") or "").strip()
    if src_cat and src_cat.lower() not in ("unclassified", "general", "n/a", "none"):
        return src_cat

    # Keyword rules based on Indian CPSE public procurement taxonomy
    text = f"{source.get('description', '')} {source.get('specification', '')} {source.get('material_type', '')}".lower()

    if any(k in text for k in ["cable", "wire", "conductor", "armoured", "unarmoured", "core"]):
        return "Electrical & Cables"
    if any(k in text for k in ["valve", "actuator", "ball valve", "gate valve", "globe valve", "check valve"]):
        return "Valves & Actuators"
    if any(k in text for k in ["pipe", "tubing", "seamless pipe", "erw pipe"]):
        return "Piping & Tubing"
    if any(k in text for k in ["elbow", "tee", "reducer", "flange", "fitting", "nipple", "coupling"]):
        return "Piping & Tubing Fittings"
    if any(k in text for k in ["bolt", "nut", "screw", "washer", "stud", "fastener", "hex head"]):
        return "Fasteners & Mechanical Hardware"
    if any(k in text for k in ["pump", "impeller", "casing", "compressor", "turbine", "rotating"]):
        return "Pumps & Rotating Equipment"
    if any(k in text for k in ["gasket", "seal", "o-ring", "mechanical seal", "packing"]):
        return "Seals & Gaskets"
    if any(k in text for k in ["oil", "transformer oil", "lubricant", "grease", "insulating oil"]):
        return "Electrical & Insulating Oils"
    if any(k in text for k in ["bearing", "bushing", "ball bearing", "roller bearing"]):
        return "Bearings & Power Transmission"

    return "Unclassified"


class CanonicalMaterialService:
    """
    Manages the Canonical Material / Common National Material Code module.
    Features:
    - Deterministic NMM-XXXXXX code generation
    - Cross-enterprise multi-CPSE provenance aggregation
    - Full traceability tree visualization
    - Search, category, CPSE, and approval status filters
    """

    def __init__(self, db_path: Optional[Path] = None):
        self.project_root = PROJECT_ROOT
        self.db_path = db_path or (
            self.project_root / "outputs" / "analysis" / "cpse_master.db"
        )
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self._ensure_schema_and_seed()

    def _get_connection(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.db_path)
        conn.row_factory = sqlite3.Row
        return conn

    def _ensure_schema_and_seed(self) -> None:
        """
        Migrates canonical_materials table to support the full NMM schema
        and seeds deterministic prototype codes with cross-enterprise links.
        """
        with self._get_connection() as conn:
            cur = conn.cursor()

            # Ensure all 6 base tables exist
            cur.executescript(CREATE_TABLES_SQL)

            # Check if national_material_code column exists in canonical_materials
            cur.execute("PRAGMA table_info(canonical_materials)")
            columns = [c[1] for c in cur.fetchall()]

            if "national_material_code" not in columns:
                # Migrate canonical_materials table cleanly
                cur.execute(
                    """
                    CREATE TABLE IF NOT EXISTS canonical_materials_new (
                        id INTEGER PRIMARY KEY AUTOINCREMENT,
                        national_material_code TEXT UNIQUE NOT NULL,
                        canonical_code TEXT UNIQUE,
                        standardized_description TEXT NOT NULL,
                        canonical_description TEXT,
                        category TEXT,
                        material_type TEXT,
                        standard_specification TEXT,
                        standard_uom TEXT,
                        technical_attributes TEXT,
                        approval_status TEXT DEFAULT 'APPROVED',
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    );
                    """
                )
                cur.execute("DROP TABLE IF EXISTS canonical_materials")
                cur.execute("ALTER TABLE canonical_materials_new RENAME TO canonical_materials")
                conn.commit()

            # Seed / Upsert the 8 default canonical prototype items
            for idx, item in enumerate(DEFAULT_PROTOTYPE_CANONICALS, start=1):
                cur.execute(
                    """
                    INSERT INTO canonical_materials (
                        national_material_code, canonical_code, standardized_description,
                        canonical_description, category, material_type,
                        standard_specification, standard_uom, technical_attributes, approval_status
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    ON CONFLICT(national_material_code) DO UPDATE SET
                        canonical_code = excluded.canonical_code,
                        standardized_description = excluded.standardized_description,
                        canonical_description = excluded.canonical_description,
                        category = excluded.category,
                        material_type = excluded.material_type,
                        standard_specification = excluded.standard_specification,
                        standard_uom = excluded.standard_uom,
                        technical_attributes = excluded.technical_attributes,
                        approval_status = excluded.approval_status,
                        updated_at = CURRENT_TIMESTAMP
                    """,
                    (
                        item["national_material_code"],
                        item["canonical_code"],
                        item["standardized_description"],
                        item["standardized_description"],
                        item["category"],
                        item["material_type"],
                        item["standard_specification"],
                        item["standard_uom"],
                        json.dumps(item["technical_attributes"]),
                        item["approval_status"],
                    ),
                )

            # Ensure cross-enterprise mappings reflect NMM codes
            self._ensure_sample_mappings(cur)
            conn.commit()

