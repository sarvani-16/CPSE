    def get_next_nmm_code(self) -> str:
        """
        Determines the next deterministic prototype NMM code:
        Queries canonical_materials, extracts the maximum numeric suffix, and adds 1.
        e.g., if max is NMM-000008 -> returns NMM-000009.
        Safe against gaps and deleted records.
        """
        with self._get_connection() as conn:
            cur = conn.cursor()
            cur.execute("SELECT national_material_code FROM canonical_materials WHERE national_material_code LIKE 'NMM-%'")
            rows = cur.fetchall()
            max_num = 0
            for r in rows:
                code_str = r[0] if isinstance(r, (list, tuple)) else r["national_material_code"]
                parts = code_str.split("-")
                if len(parts) >= 2 and parts[1].isdigit():
                    val = int(parts[1])
                    if val > max_num:
                        max_num = val
            next_num = max_num + 1
            return f"NMM-{next_num:06d}"

    def find_existing_canonical_match(
        self,
        source_text: str,
        threshold: float = 0.75,
    ) -> Optional[Dict[str, Any]]:
        """
        Checks whether an existing canonical material matches source_text closely enough
        to prevent duplicate canonical prototype creation (idempotency requirement).
        """
        from backend.app.ml.hybrid_engine import get_hybrid_engine
        engine = get_hybrid_engine()

        with self._get_connection() as conn:
            cur = conn.cursor()
            cur.execute(
                """
                SELECT id, national_material_code, canonical_code,
                       standardized_description, category, material_type,
                       standard_specification, standard_uom, approval_status
                FROM canonical_materials
                """
            )
            canonicals = [dict(r) for r in cur.fetchall()]

            best_match = None
            best_score = -1.0
            for can in canonicals:
                # Compare against standardized description
                res1 = engine.compare(source_text, can["standardized_description"])
                score = res1["hybrid_score"]
                res = res1

                # Also compare against description + spec if spec exists
                if can.get("standard_specification"):
                    res2 = engine.compare(
                        source_text,
                        f"{can['standardized_description']} {can['standard_specification']}"
                    )
                    if res2["hybrid_score"] > score:
                        score = res2["hybrid_score"]
                        res = res2

                if score > best_score:
                    best_score = score
                    if (res["match_decision"] == "MATCH" or score >= threshold) and not res["technical_tokens"]["has_conflicts"]:
                        best_match = can

            if best_match and (best_score >= threshold):
                return best_match
            return None

    def create_prototype_canonical(
        self,
        source_material: Dict[str, Any],
        performed_by: str = "AI_STANDARDIZATION_ENGINE",
        reason: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Creates a new Prototype Common Material Code (NMM Series) for previously unseen materials:
        1. Checks whether a sufficiently similar canonical material already exists (idempotency).
        2. Generates the next deterministic NMM code (e.g. NMM-000009).
        3. Synthesizes canonical description without hallucinating technical attributes.
        4. Sets explicit prototype status: PENDING / requires validation.
        5. Persists linkage in material_mappings with match_status = 'PENDING'.
        6. Logs immutable audit trail entry: CREATE_CANONICAL_CODE.
        """
        src_desc = (source_material.get("description") or "").strip()
        if not src_desc:
            raise ValueError("Cannot create canonical material: missing source description.")

        src_text = src_desc
        if source_material.get("specification"):
            src_text += f" {source_material['specification']}"
        if source_material.get("material_grade"):
            src_text += f" {source_material['material_grade']}"

        # 1. Idempotency check: Reuse existing canonical if close match exists
        existing = self.find_existing_canonical_match(src_text, threshold=0.75)
        if existing:
            # If source_material has an id, ensure mapping exists
            src_id = source_material.get("id")
            if src_id:
                with self._get_connection() as conn:
                    cur = conn.cursor()
                    cur.execute(
                        "SELECT id FROM material_mappings WHERE source_material_id = ?",
                        (src_id,),
                    )
                    existing_map = cur.fetchone()
                    if not existing_map:
                        cur.execute(
                            """
                            INSERT INTO material_mappings (
                                source_material_id, cpse_name, original_material_code,
                                original_description, canonical_material_code, canonical_description,
                                match_status, confidence, reviewer
                            ) VALUES (?, ?, ?, ?, ?, ?, 'PENDING', 1.0, ?)
                            """,
                            (
                                src_id,
                                source_material.get("cpse_name", "CPSE"),
                                source_material.get("material_code", "N/A"),
                                src_desc,
                                existing["national_material_code"],
                                existing["standardized_description"],
                                performed_by,
                            ),
                        )
                        conn.commit()
            return existing

        # 2. Generate next deterministic NMM code
        nmm_code = self.get_next_nmm_code()

        # 3. Canonical description & category
        std_desc = generate_canonical_description(source_material)
        category = determine_canonical_category(source_material)

        # 4. Technical attributes
        from backend.app.ml.text_normalizer import extract_technical_tokens
        tech_tokens = extract_technical_tokens(src_text)
        tech_attrs = {
            "code_type": "Prototype Common Material Code",
            "status_note": "AI-generated prototype — requires validation",
            "source_reference": f"{source_material.get('cpse_name', 'CPSE')}:{source_material.get('material_code', 'N/A')}",
            "material_grade": source_material.get("material_grade") or "N/A",
            "dimensions": source_material.get("dimensions") or "N/A",
            "specification": source_material.get("specification") or "N/A",
            "extracted_tokens": list(tech_tokens),
        }

        # 5. Persist to canonical_materials
        with self._get_connection() as conn:
            cur = conn.cursor()
            cur.execute(
                """
                INSERT INTO canonical_materials (
                    national_material_code, canonical_code, standardized_description,
                    canonical_description, category, material_type,
                    standard_specification, standard_uom, technical_attributes,
                    approval_status
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'PENDING')
                """,
                (
                    nmm_code,
                    nmm_code,
                    std_desc,
                    std_desc,
                    category,
                    source_material.get("material_type") or "AI-Generated Prototype Standard",
                    source_material.get("specification") or "Pending Standardization",
                    source_material.get("unit_of_measure") or "EA",
                    json.dumps(tech_attrs),
                ),
            )
            canonical_id = cur.lastrowid

            # 6. Persist initial mapping in material_mappings if source has an ID
            src_id = source_material.get("id")
            if src_id:
                cur.execute(
                    """
                    SELECT id FROM material_mappings WHERE source_material_id = ?
                    """,
                    (src_id,),
                )
                existing_map = cur.fetchone()
                if existing_map:
                    cur.execute(
                        """
                        UPDATE material_mappings
                        SET canonical_material_code = ?,
                            canonical_description = ?,
                            match_status = 'PENDING',
                            confidence = 1.0,
                            reviewer = ?
                        WHERE id = ?
                        """,
                        (nmm_code, std_desc, performed_by, existing_map[0]),
                    )
                else:
                    cur.execute(
                        """
                        INSERT INTO material_mappings (
                            source_material_id, cpse_name, original_material_code,
                            original_description, canonical_material_code, canonical_description,
                            match_status, confidence, reviewer
                        ) VALUES (?, ?, ?, ?, ?, ?, 'PENDING', 1.0, ?)
                        """,
                        (
                            src_id,
                            source_material.get("cpse_name", "CPSE"),
                            source_material.get("material_code", "N/A"),
                            src_desc,
                            nmm_code,
                            std_desc,
                            performed_by,
                        ),
                    )
            conn.commit()

        # 7. Record immutable audit log
        from backend.app.cpse.audit_service import get_audit_service
        audit_svc = get_audit_service()
        audit_reason = reason or "Created prototype canonical material because no suitable existing canonical material met the configured matching threshold."
        audit_svc.record_log(
            action="CREATE_CANONICAL_CODE",
            entity_type="canonical_materials",
            entity_id=nmm_code,
            old_value=None,
            new_value=json.dumps({
                "national_material_code": nmm_code,
                "standardized_description": std_desc,
                "category": category,
                "approval_status": "PENDING",
                "status_note": "AI-generated prototype — requires validation",
                "source_material_id": src_id,
                "source_cpse": source_material.get("cpse_name"),
                "source_code": source_material.get("material_code"),
            }),
            performed_by=performed_by,
            reason=audit_reason,
            details={
                "code": nmm_code,
                "description": std_desc,
                "category": category,
                "source_material_id": src_id,
            },
        )

        return {
            "id": canonical_id,
            "national_material_code": nmm_code,
            "canonical_code": nmm_code,
            "standardized_description": std_desc,
            "category": category,
            "material_type": source_material.get("material_type") or "AI-Generated Prototype Standard",
            "approval_status": "PENDING",
            "code_type_label": "Prototype Common Material Code",
            "status_note": "AI-generated prototype — requires validation",
            "source_reference": f"{source_material.get('cpse_name', 'CPSE')}:{source_material.get('material_code', 'N/A')}",
        }

    def get_canonical_materials(
        self,
        search: Optional[str] = None,
        category: Optional[str] = None,
        approval_status: Optional[str] = None,
        cpse_name: Optional[str] = None,
        page: int = 1,
        page_size: int = 20,
    ) -> Dict[str, Any]:
        """
        GET /api/canonical-materials
        Retrieves paginated list of canonical materials with mapped CPSEs,
        original codes count/summary, confidence, and approval status.
        """
        page = max(1, page)
        page_size = max(1, min(100, page_size))
        offset = (page - 1) * page_size

        conditions = []
        params = []

        if search and search.strip():
            s = f"%{search.strip().lower()}%"
            conditions.append(
                """(
                    LOWER(c.national_material_code) LIKE ?
                    OR LOWER(c.standardized_description) LIKE ?
                    OR LOWER(c.category) LIKE ?
                    OR LOWER(c.standard_specification) LIKE ?
                    OR LOWER(c.technical_attributes) LIKE ?
                )"""
            )
            params.extend([s, s, s, s, s])

        if category and category.strip() and category.upper() != "ALL":
            conditions.append("c.category = ?")
            params.append(category.strip())

        if approval_status and approval_status.strip() and approval_status.upper() != "ALL":
            conditions.append("c.approval_status = ?")
            params.append(approval_status.strip().upper())

        where_clause = f"WHERE {' AND '.join(conditions)}" if conditions else ""

        with self._get_connection() as conn:
            cur = conn.cursor()

            # Distinct categories list for dropdown filter
            cur.execute("SELECT DISTINCT category FROM canonical_materials WHERE category IS NOT NULL ORDER BY category")
            categories = [r[0] for r in cur.fetchall()]

            # Total matching records count
            cur.execute(f"SELECT COUNT(*) FROM canonical_materials c {where_clause}", params)
            total = cur.fetchone()[0]

            # Fetch paginated items
            query = f"""
                SELECT
                    c.id, c.national_material_code, c.canonical_code,
                    c.standardized_description, c.category, c.material_type,
                    c.standard_specification, c.standard_uom, c.technical_attributes,
                    c.approval_status, c.created_at, c.updated_at
                FROM canonical_materials c
                {where_clause}
                ORDER BY c.national_material_code ASC
                LIMIT ? OFFSET ?
            """
            cur.execute(query, params + [page_size, offset])
            rows = cur.fetchall()

            items = []
            for row in rows:
                nmm_code = row["national_material_code"]

                # Fetch mapped CPSEs and original codes from material_mappings
                cur.execute(
                    """
                    SELECT
                        m.id as mapping_id, m.cpse_name, m.original_material_code,
                        m.original_description, m.match_status, m.confidence,
                        m.reviewer, m.timestamp,
                        s.specification, s.unit_of_measure, s.material_grade
                    FROM material_mappings m
                    LEFT JOIN source_materials s ON m.source_material_id = s.id
                    WHERE m.canonical_material_code = ?
                    ORDER BY m.cpse_name ASC
                    """,
                    (nmm_code,),
                )
                map_rows = cur.fetchall()

                # Filter by cpse_name if requested
                if cpse_name and cpse_name.strip() and cpse_name.upper() != "ALL":
                    if not any(r["cpse_name"] == cpse_name.strip() for r in map_rows):
                        continue

                mapped_cpses = sorted(list(set(r["cpse_name"] for r in map_rows)))
                original_codes = [r["original_material_code"] for r in map_rows]

                # Calculate confidence
                confidences = [r["confidence"] for r in map_rows if r["confidence"] is not None]
                avg_confidence = round(sum(confidences) / len(confidences), 4) if confidences else 0.90

                # Parse technical attributes
                try:
                    tech_attrs = json.loads(row["technical_attributes"]) if row["technical_attributes"] else {}
                except Exception:
                    tech_attrs = {}

                # Build cpse_mappings list
                cpse_mappings = []
                for m in map_rows:
                    cpse_mappings.append(
                        {
                            "mapping_id": m["mapping_id"],
                            "cpse_name": m["cpse_name"],
                            "original_material_code": m["original_material_code"],
                            "original_description": m["original_description"],
                            "specification": m["specification"] or "N/A",
                            "unit_of_measure": m["unit_of_measure"] or "N/A",
                            "material_grade": m["material_grade"] or "N/A",
                            "match_status": m["match_status"],
                            "confidence": m["confidence"],
                            "reviewer": m["reviewer"],
                            "timestamp": m["timestamp"],
                        }
                    )

                items.append(
                    {
                        "id": row["id"],
                        "national_material_code": nmm_code,
                        "code_type_label": "Prototype Common Material Code",
                        "standardized_description": row["standardized_description"],
                        "category": row["category"] or "General Equipment",
                        "material_type": row["material_type"] or "Standard Material",
                        "standard_specification": row["standard_specification"] or "National Standard Specification",
                        "standard_uom": row["standard_uom"] or "EA",
                        "technical_attributes": tech_attrs,
                        "approval_status": row["approval_status"] or "APPROVED",
                        "source_materials_count": len(map_rows),
                        "mapped_cpses": mapped_cpses,
                        "original_codes": original_codes,
                        "cpse_mappings": cpse_mappings,
                        "confidence": avg_confidence,
                        "created_at": row["created_at"],
                        "updated_at": row["updated_at"] or row["created_at"],
                    }
                )

        total_pages = (total + page_size - 1) // page_size if total > 0 else 1

        return {
            "total": total,
            "page": page,
            "page_size": page_size,
            "total_pages": total_pages,
            "categories": categories,
            "code_type": "Prototype Common Material Code",
            "disclaimer": PROTOTYPE_DISCLAIMER,
            "items": items,
        }

    def get_canonical_material_detail(self, identifier: str) -> Dict[str, Any]:
        """
        GET /api/canonical-materials/{id}
        Retrieves complete detailed record with multi-branch provenance tree:
        Common Code (NMM-000001)
        ↓
        Canonical Description
        ↓
        CPSE A → Original Code
        CPSE B → Original Code
        CPSE C → Original Code
        """
        ident = str(identifier).strip()

        with self._get_connection() as conn:
            cur = conn.cursor()

            # Search by ID or national_material_code or canonical_code
            if ident.isdigit():
                cur.execute(
                    """
                    SELECT id, national_material_code, canonical_code,
                           standardized_description, category, material_type,
                           standard_specification, standard_uom, technical_attributes,
                           approval_status, created_at, updated_at
                    FROM canonical_materials
                    WHERE id = ? OR national_material_code = ?
                    """,
                    (int(ident), f"NMM-{int(ident):06d}"),
                )
            else:
                cur.execute(
                    """
                    SELECT id, national_material_code, canonical_code,
                           standardized_description, category, material_type,
                           standard_specification, standard_uom, technical_attributes,
                           approval_status, created_at, updated_at
                    FROM canonical_materials
                    WHERE LOWER(national_material_code) = ? OR LOWER(canonical_code) = ?
                    """,
                    (ident.lower(), ident.lower()),
                )

            row = cur.fetchone()
            if not row:
                raise ValueError(f"Canonical material with identifier '{identifier}' not found.")

            nmm_code = row["national_material_code"]

            # Parse technical attributes
            try:
                tech_attrs = json.loads(row["technical_attributes"]) if row["technical_attributes"] else {}
            except Exception:
                tech_attrs = {}

            # Fetch mapped source materials with complete details
            cur.execute(
                """
                SELECT
                    m.id as mapping_id, m.cpse_name, m.original_material_code,
                    m.original_description, m.match_status, m.confidence,
                    m.reviewer, m.timestamp,
                    s.id as source_id, s.specification, s.unit_of_measure,
                    s.material_grade, s.dimensions, s.manufacturer,
                    s.part_number, s.source_file, s.created_at as ingested_at
                FROM material_mappings m
                LEFT JOIN source_materials s ON m.source_material_id = s.id
                WHERE m.canonical_material_code = ?
                ORDER BY m.cpse_name ASC, m.original_material_code ASC
                """,
                (nmm_code,),
            )
            map_rows = cur.fetchall()

            source_materials = []
            cpse_mappings = []
            traceability_branches = []

            for r in map_rows:
                src_item = {
                    "source_material_id": r["source_id"],
                    "cpse_name": r["cpse_name"],
                    "material_code": r["original_material_code"],
                    "description": r["original_description"],
                    "specification": r["specification"] or "N/A",
                    "unit_of_measure": r["unit_of_measure"] or "N/A",
                    "material_grade": r["material_grade"] or "N/A",
                    "dimensions": r["dimensions"] or "N/A",
                    "manufacturer": r["manufacturer"] or "N/A",
                    "part_number": r["part_number"] or "N/A",
                    "source_file": r["source_file"] or "N/A",
                    "ingested_at": r["ingested_at"],
                }
                source_materials.append(src_item)

                mapping_item = {
                    "mapping_id": r["mapping_id"],
                    "cpse_name": r["cpse_name"],
                    "original_material_code": r["original_material_code"],
                    "original_description": r["original_description"],
                    "match_status": r["match_status"],
                    "confidence": r["confidence"],
                    "reviewer": r["reviewer"],
                    "timestamp": r["timestamp"],
                }
                cpse_mappings.append(mapping_item)

                # Traceability Tree Branch
                traceability_branches.append(
                    {
                        "cpse_name": r["cpse_name"],
                        "original_code": r["original_material_code"],
                        "original_description": r["original_description"],
                        "specification": r["specification"] or "N/A",
                        "unit_of_measure": r["unit_of_measure"] or "N/A",
                        "material_grade": r["material_grade"] or "N/A",
                        "dimensions": r["dimensions"] or "N/A",
                        "match_status": r["match_status"],
                        "confidence": r["confidence"],
                        "reviewer": r["reviewer"],
                        "timestamp": r["timestamp"],
                    }
                )

            # Average confidence
            confidences = [r["confidence"] for r in map_rows if r["confidence"] is not None]
            avg_confidence = round(sum(confidences) / len(confidences), 4) if confidences else 0.90

            # Traceability tree structure requested by user
            traceability_tree = {
                "common_code": nmm_code,
                "code_type": "Prototype Common Material Code",
                "canonical_description": row["standardized_description"],
                "category": row["category"],
                "material_type": row["material_type"],
                "standard_specification": row["standard_specification"],
                "standard_uom": row["standard_uom"],
                "approval_status": row["approval_status"],
                "branches": traceability_branches,
            }

            return {
                "id": row["id"],
                "national_material_code": nmm_code,
                "code_type_label": "Prototype Common Material Code",
                "standardized_description": row["standardized_description"],
                "category": row["category"] or "General Equipment",
                "material_type": row["material_type"] or "Standard Material",
                "standard_specification": row["standard_specification"] or "National Standard Specification",
                "standard_uom": row["standard_uom"] or "EA",
                "technical_attributes": tech_attrs,
                "approval_status": row["approval_status"] or "APPROVED",
                "confidence": avg_confidence,
                "source_materials": source_materials,
                "cpse_mappings": cpse_mappings,
                "traceability_tree": traceability_tree,
                "created_at": row["created_at"],
                "updated_at": row["updated_at"] or row["created_at"],
                "disclaimer": PROTOTYPE_DISCLAIMER,
            }


